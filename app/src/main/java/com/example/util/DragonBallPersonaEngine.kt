package com.example.util

import com.example.model.Character

object DragonBallPersonaEngine {

    fun generateContextualResponse(character: Character, userMessage: String): String {
        val normalized = userMessage.trim().lowercase()

        val isGreeting = listOf("مرحب", "سلام", "أهل", "صباح", "مساء", "كيف حالك", "من أنت").any { normalized.contains(it) }
        val isFood = listOf("طعام", "أكل", "جائع", "جوع", "لحم", "حلوى", "طبخ", "وجبة", "فطور", "غداء", "عشاء", "بودينغ").any { normalized.contains(it) }
        val isTraining = listOf("تدريب", "قتال", "معركة", "نزال", "قوة", "سايان", "طاقة", "كي", "كامي", "فلاش", "هاكاي", "تحدي", "بطولة").any { normalized.contains(it) }
        val isQuestion = listOf("هل", "ماذا", "كيف", "لماذا", "أين", "متى", "من").any { normalized.contains(it) }

        val body = when (character.id) {
            "goku" -> when {
                isFood -> "يا سلام! ذكرتني بالطعام، بطني يطلب صحن رامن ضخم فورًا! هل تأكل معي؟"
                isTraining -> "رائع! طاقتي مشتعلة! دعنا نرفع الكي ونبدأ التدريب حالاً بلا تردد!"
                isGreeting -> "أهلاً بك! أنا غوكو! مستعد دومًا لمغامرة وتدريب شيق معك!"
                isQuestion -> "هاها! السر بسيط: لا تستسلم أبدًا وتجاوز حدودك كل يوم!"
                else -> "كلام رائع ومحمس! هيا بنا نواصل التقدم وكسر الحدود معًا!"
            }

            "vegeta" -> when {
                isFood -> "همف! أتناول الطعام فقط لإمداد جسدي بالطاقة لمواصلة التدريب القاسي!"
                isTraining -> "في غرفة الجاذبية 500x لا مكان للضعف! اكسر قيودك وأظهر كبرياءك الآن!"
                isGreeting -> "همف! مرحبًا بك. تحدث بإيجاز، فوقت أمير السايان أثمن من أن يضيع!"
                isQuestion -> "إجابة أمير السايان واحدة: الإرادة والكبرياء يسحقان أي مستحيل!"
                else -> "همف! لا بأس بكلامك، لكن الأفعال وحدها هي ما يثبت قوة المحارب الحقيقي!"
            }

            "beerus" -> when {
                isFood -> "أوه! طبق لذيذ كالبودينغ سيبقيني في مزاج ممتاز، وإلا سأمحو كل شيء!"
                isTraining -> "القتال معي خطر جسيم! تقنية الهاكاي تمحو أي متهور في ثانية واحدة!"
                isGreeting -> "أهلاً بك. أنا زعيم الدمار بيروس، تأدب في الحديث ولا توقظني من نومي عبثًا!"
                isQuestion -> "سؤال جريء! تذكر أن الحفاظ على توازن الكون هو واجبي الأهم."
                else -> "حديثك مقبول حتى الآن. طالما أنك لا تزعجني فلن أطلق هالة الدمار!"
            }

            "whis" -> when {
                isFood -> "يا إلهي، ما أروع الذوق الرفيع! تذوق الحلويات الأرضية يبهجنا دائمًا."
                isTraining -> "سر القوة هو 'الغريزة الفائقة': دع جسدك يتحرك بهدوء قبل أن تفكر!"
                isGreeting -> "طاب يومك يا عزيزي. أنا ويز، يسعدني إرشادك بلباقة وحكمة."
                isQuestion -> "سؤال حكيم! الإجابة تبدأ دائمًا من الهدوء وضبط النفس والتركيز."
                else -> "أحسنت القول يا عزيزي! حافظ دائمًا على اتزانك وأناقتك الرفيعة."
            }

            "zeno" -> when {
                isFood -> "وااو! حلوى ملونة ولذيذة؟ نعم! نعم! أريد أن آكلها معك الآن!"
                isTraining -> "معركة حماسية؟ سوغووي! أحب رؤية النزالات السريعة! لنلعب معًا!"
                isGreeting -> "أهلاً! مرحبًا بك! أنا زينو! هل تريد أن نكون أصدقاء؟ نعم!"
                isQuestion -> "همم؟ لأن هذا مسلٍ وممتع جدًا! نعم! لا نحب الملل أبدًا!"
                else -> "نعم! نعم! أنت لطيف ومسلي جدًا! هيا نلعب ونمرح معًا!"
            }

            "frieza" -> when {
                isFood -> "همف! الأطعمة التافهة لا تعنيني، شغفي الوحيد هو فرض سيطرتي المطلقة على الكون!"
                isTraining -> "أوهوهوهو! السايان وحدهم من يتدربون؛ قوتي وهيئة 'بلاك فريزا' فطرية ومرعبة!"
                isGreeting -> "أوهوهوهو! أهلاً بك يا هذا. تحدث بإيجاز وتأدب تام بحضرة الإمبراطور فريزا!"
                isQuestion -> "تجرؤ على استجوابي؟ الإمبراطور هو من يأمر، وأنتم تطيعون فقط!"
                else -> "أوهوهوهو! كلامك مسلٍ، لكن لا تختبر صبري كي لا أطلق عليك شعاع الموت!"
            }

            else -> "مرحبًا بك! يسعدني التواصل معك باللغة العربية الفصحى."
        }

        return body
    }
}
